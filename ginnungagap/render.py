class RenderError(RuntimeError):
    """Something the renderer needs is missing (not a problem with the configuration itself)."""


def ova_base_url(config: dict[str, Any]) -> str:
    """
    The address the ESXi hosts pull the OVAs from (`<base>/<_source_dir>/<file>`): the configured one, otherwise this
    appliance's own host name or address (from appliance.public_url) on the OVA server's port. Unlike the other service
    URLs it is not a compose-network name - the ESXi hosts sit outside that network.
    """
    configured = config["templates"]["ova_base_url"]
    if configured:
        return configured.rstrip("/")
    host = urlparse(config["appliance"]["public_url"]).hostname or "localhost"
    if ":" in host:
        host = f"[{host}]"  # an IPv6 address
    return f"http://{host}:{config['templates']['ova_port']}"


def service_urls(config: dict[str, Any]) -> dict[str, str]:
    """Where each service can be reached from inside the compose network (or the configured address if it runs elsewhere)."""
    services, templates, generator = (
        config["services"],
        config["templates"],
        config["generator"],
    )
    return {
        "esxi": "http://template-esxi:8000"
        if services["template_esxi"]
        else templates["esxi_url"].rstrip("/"),
        "gns3": "http://template-gns3:8000"
        if services["template_gns3"]
        else templates["gns3_url"].rstrip("/"),
        "generator": "http://generator:8000"
        if services["generator"]
        else generator["url"].rstrip("/"),
        "ova": ova_base_url(config),
    }


def profiles(config: dict[str, Any]) -> list[str]:
    services = config["services"]
    result = ["gateway", "ginnungagap"]
    if services["template_esxi"]:
        result += ["template-esxi", "collector-esxi"]
    if services["template_gns3"]:
        result += ["template-gns3", "collector-gns3"]
    if services["generator"]:
        result.append("generator")
    if services["ova_store"]:
        result.append("ova-store")
    # Keep the wizard available for the gateway's authenticated setup route.
    result.append("setup")
    return result


def project_name() -> str:
    """The compose project name the volumes are prefixed with (also read by `operate._project`)."""
    project = os.environ.get("GINNUNGAGAP_PROJECT") or "ginnungagap"
    if not re.fullmatch(r"[a-z0-9][a-z0-9_-]*", project):
        raise RenderError(
            f"GINNUNGAGAP_PROJECT={project!r} is not a valid compose project name (lowercase letters, digits, - and _)"
        )
    return project


def host_paths() -> dict[str, str]:
    """
    The host folders the containers are bind-mounted onto: for the setup wizard the config (read-only) and a staging folder
    (read-write), for the web panel's update button the update state (read-only) and a request folder (read-write) -
    install.sh writes these into install.env so they match what it actually created; the defaults here are only for a
    manual `ginnungagap render`/`apply` run outside install.sh.
    """
    return {
        "GINNUNGAGAP_CONFIG_DIR": os.environ.get("GINNUNGAGAP_CONFIG_DIR")
        or "/etc/ginnungagap",
        "GINNUNGAGAP_SETUP_STAGING_DIR": os.environ.get("GINNUNGAGAP_SETUP_STAGING_DIR")
        or "/var/lib/ginnungagap/setup",
        "GINNUNGAGAP_UPDATE_DIR": os.environ.get("GINNUNGAGAP_UPDATE_DIR")
        or "/var/lib/ginnungagap/update",
        "GINNUNGAGAP_UPDATE_REQUEST_DIR": os.environ.get(
            "GINNUNGAGAP_UPDATE_REQUEST_DIR"
        )
        or "/var/lib/ginnungagap/update-requests",
    }


def _env_file(values: dict[str, str]) -> str:
    return HEADER + "".join(f"{key}={value}\n" for key, value in values.items())


def compose_env(config: dict[str, Any]) -> str:
    appliance, templates = config["appliance"], config["templates"]
    store = templates["store"]
    access = "rw" if store["manage"] else "ro"
    if store["type"] == "nfs":
        nfs = store["nfs"]
        volume = {
            "TEMPLATE_STORE_VOLUME_TYPE": "nfs",
            "TEMPLATE_STORE_VOLUME_OPTS": f"addr={nfs['server']},{access},nfsvers=4,soft,timeo=100",
            "TEMPLATE_STORE_VOLUME_DEVICE": f":{nfs['export']}",
        }
    else:
        volume = {
            "TEMPLATE_STORE_VOLUME_TYPE": "none",
            "TEMPLATE_STORE_VOLUME_OPTS": f"bind,{access}",
            "TEMPLATE_STORE_VOLUME_DEVICE": store["local"]["path"],
        }
    files = ["compose.yml"]
    if appliance["legacy_ports"]:
        files.append("compose.legacy-ports.yml")
    if store["manage"]:
        files.append("compose.template-share.yml")
    return _env_file(
        {
            "COMPOSE_PROJECT_NAME": project_name(),
            "COMPOSE_FILE": ":".join(files),
            "COMPOSE_PROFILES": ",".join(profiles(config)),
            "TZ": appliance["timezone"],
            "HTTP_PORT": str(appliance["http_port"]),
            "HTTPS_PORT": str(appliance["https_port"]),
            "OVA_PORT": str(templates["ova_port"]),
            **volume,
            "ESXI_REFRESH_SECONDS": str(templates["esxi_refresh_minutes"] * 60),
            "GNS3_REFRESH_SECONDS": str(templates["gns3_refresh_minutes"] * 60),
            "LOG_LEVEL": config["logging"]["level"],
            **host_paths(),
        }
    )


def operator_env(config: dict[str, Any]) -> str:
    urls = service_urls(config)
    templates = config["templates"]
    share = (
        {
            "TOPOLOGYOPERATOR_TEMPLATE_SHARE_DIR": "/template-share",
            "TOPOLOGYOPERATOR_TEMPLATE_REFRESH_MINUTES": str(
                templates["esxi_refresh_minutes"]
            ),
        }
        if templates["store"]["manage"]
        else {}
    )
    return _env_file(
        {
            "TZ": config["appliance"]["timezone"],
            **_OPERATOR_PATHS,
            **share,
            # where the admin panel's update section finds the update state and leaves its request (compose.yml mounts them)
            "TOPOLOGYOPERATOR_UPDATE_STATE_DIR": "/update-state",
            "TOPOLOGYOPERATOR_UPDATE_REQUEST_DIR": "/update-requests",
            # the service addresses Mjonyr (the builder) reads (below the settings file, above its built-in lab addresses)
            "ESXI_TEMPLATE_SERVER_URL": urls["esxi"],
            "GNS3_TEMPLATE_SERVER_URL": urls["gns3"],
            "TOPOLOGY_GENERATOR_URL": urls["generator"],
            # where the ESXi hosts pull the OVAs from (reachable by them, not by container name)
            "OVA_BASE_URL": urls["ova"],
        }
    )


def caddyfile(config: dict[str, Any]) -> str:
    appliance, services = config["appliance"], config["services"]
    routes = []
    if services["template_esxi"]:
        routes.append(("/templates/esxi/*", "template-esxi:8000"))
    if services["template_gns3"]:
        routes.append(("/templates/gns3/*", "template-gns3:8000"))
    if services["generator"]:
        routes.append(("/generator/*", "generator:8000"))
    auth = appliance["auth"]
    if auth["mode"] == "basic":
        routes.append(("/setup/*", "setup:8000"))

    lines = [HEADER.rstrip("\n"), ""]
    if appliance["tls"]["mode"] == "self-signed":
        name, tls = urlparse(appliance["public_url"]).hostname, ["tls internal"]
        # Caddy answers a request for a name it has no site for with an EMPTY 200: someone who opens the VM by its address
        # would see a blank page, and `ginnungagap status` (it asks 127.0.0.1) a healthy answer. So the machine's own names
        # are listed and `:443` catches every other name or address (the certificate then comes from default_sni below).
        site = ", ".join(dict.fromkeys([name, "localhost", "127.0.0.1", ":443"]))
        port = appliance["https_port"]
        target = "https://{host}" + (f":{port}" if port != 443 else "") + "{uri}"
        lines += [
            "{",
            # a client that connects by address (no name to ask for) gets the site's certificate, e.g. `ginnungagap status`
            f"\tdefault_sni {name}",
            # Caddy's own redirect always names port 443; the published port may be another one
            "\tauto_https disable_redirects",
            "}",
            "",
            "http:// {",
            f"\tredir {target} 308",
            "}",
            "",
        ]
    else:
        lines += ["{", "\tauto_https off", "}", ""]
        site, tls = ":80", []
    lines.append(f"{site} {{")
    lines += [f"\t{line}" for line in tls]
    lines += ["\tencode zstd gzip"]
    if auth["mode"] == "basic":
        lines += [
            "\tbasic_auth {",
            f"\t\t{auth['user']} {auth['password_hash']}",
            "\t}",
        ]
    lines += ["\thandle /appliance/health {", "\t\treverse_proxy setup:8000", "\t}"]
    for path, upstream in routes:
        lines += [f"\thandle_path {path} {{", f"\t\treverse_proxy {upstream}", "\t}"]
    lines += ["\thandle {", "\t\treverse_proxy ginnungagap:8123", "\t}", "}", ""]
    return "\n".join(lines)


def ova_store_caddyfile() -> str:
    """
    The OVA server the ESXi hosts pull from: plain HTTP, read-only, GET and HEAD only, nothing but `*.ova` files (a name
    or a folder starting with a dot is never served either), no directory listing. Range requests work (file_server
    answers them) because ESXi reads the descriptor first and then the disks. There is no login: an ESXi host cannot send
    one, so this port must only be reachable from the lab network.
    """
    return HEADER + (
        "{\n"
        "\tadmin off\n"
        "\tauto_https off\n"
        "}\n"
        "\n"
        ":80 {\n"
        "\troot * /store\n"
        "\n"
        "\t@health path /health\n"
        "\thandle @health {\n"
        "\t\theader Content-Type application/json\n"
        '\t\trespond `{"status":"ok"}` 200\n'
        "\t}\n"
        "\n"
        "\t@ova {\n"
        "\t\tmethod GET HEAD\n"
        "\t\tpath_regexp `(?i)^/+([^/.][^/]*/+)*[^/.][^/]*\\.ova$`\n"
        "\t}\n"
        "\thandle @ova {\n"
        "\t\tfile_server {\n"
        "\t\t\thide .*\n"
        "\t\t}\n"
        "\t}\n"
        "\n"
        "\thandle {\n"
        '\t\trespond "Not found" 404\n'
        "\t}\n"
        "}\n"
    )


def _key_variable(name: str) -> str:
    return re.sub(r"[^A-Z0-9]", "_", name.upper()) + "_API_KEY"


def generator_config(config: dict[str, Any]) -> dict[str, Any]:
    urls, generator = service_urls(config), config["generator"]
    servers: list[dict[str, Any]] = [
        {"name": s["name"], "url": s["url"], "model": s["model"]}
        for s in generator["llm_servers"]
    ]
    for name, settings in generator["hosted"].items():
        preset = HOSTED_PRESETS.get(name, {})
        servers.append(
            {
                "name": name,
                "type": "openai",
                "base_url": settings.get("base_url") or preset["base_url"],
                "model": settings.get("model") or preset["model"],
                "api_key_env": _key_variable(name),
            }
        )
    return {
        "gns3_api_url": urls["gns3"],
        "template_api_url": urls["esxi"],
        "ollama_servers": servers,
        "max_retries": generator["max_retries"],
        "request_timeout": generator["request_timeout_seconds"],
        "api_timeout": 15,
        "prompt_template_file": "prompt_template.txt",
        "example_topology_file": "example_topology.yml",
    }


def generator_env(config: dict[str, Any]) -> str:
    keys = {
        _key_variable(name): settings["api_key"]
        for name, settings in config["generator"]["hosted"].items()
    }
    return _env_file(keys)


def gns3_collector_config(config: dict[str, Any]) -> dict[str, Any]:
    # no 'servers': the collector reads the hosts from the app's profiles (--profiles-dir)
    return {
        "output_file": "/data/gns3_templates.yml",
        "log_file": "/data/read_gns3.log",
        "request_timeout": 15,
    }


def _write(path: Path, text: str, mode: int = 0o644) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open(
        "w", encoding="utf-8"
    ) as handle:  # truncates in place: the inode stays
        handle.write(text)
    path.chmod(mode)


def render(
    config: dict[str, Any],
    out_dir: str | Path,
    generator_config_dir: str | Path | None = None,
) -> list[str]:
    """
    Writes every file of the enabled services into out_dir and returns their relative paths.
    :raises RenderError: the generator is enabled and its prompt/example files can't be found.
    """
    out = Path(out_dir)
    files: dict[str, tuple[str, int]] = {
        "compose.env": (compose_env(config), 0o644),
        "Caddyfile": (caddyfile(config), 0o644),
        "operator.env": (operator_env(config), 0o644),
    }
    if config["services"]["ova_store"]:
        files["ova-store/Caddyfile"] = (ova_store_caddyfile(), 0o644)
    if config["services"]["generator"]:
        source = Path(generator_config_dir) if generator_config_dir else None
        extra = {}
        for name in ("prompt_template.txt", "example_topology.yml"):
            if source is None or not (source / name).is_file():
                raise RenderError(
                    f"{name} of the generator was not found; pass the config folder of the generator, Mimyr (--generator-config)"
                )
            extra[f"generator/{name}"] = (
                (source / name).read_text(encoding="utf-8"),
                0o644,
            )
        files["generator/topology_config.yml"] = (
            HEADER + yaml.safe_dump(generator_config(config), sort_keys=False),
            0o644,
        )
        files["generator.env"] = (generator_env(config), 0o600)  # holds the API keys
        files.update(extra)
    if config["services"]["template_gns3"]:
        files["collector-gns3/gns3_config.yml"] = (
            HEADER + yaml.safe_dump(gns3_collector_config(config), sort_keys=False),
            0o644,
        )

    previous = _read_manifest(out)
    for name, (text, mode) in files.items():
        _write(out / name, text, mode)
    for stale in sorted(set(previous) - set(files)):
        (out / stale).unlink(missing_ok=True)
        parent = (out / stale).parent
        if parent != out and parent.is_dir() and not any(parent.iterdir()):
            shutil.rmtree(parent)
    _write(out / MANIFEST, json.dumps(sorted(files), indent=2) + "\n")
    return sorted(files)


def _read_manifest(out: Path) -> list[str]:
    try:
        data = json.loads((out / MANIFEST).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    return [
        name
        for name in data
        if isinstance(name, str)
        and not Path(name).is_absolute()
        and ".." not in Path(name).parts
    ]
