"""
Turns the one configuration into the files each service reads.

Every service keeps its own native configuration; nothing here couples services, it only writes each one's own file and
the URLs between them. Files are rewritten in place (same inode) because Docker bind-mounts single files by inode, and a
file that is no longer produced is removed again (tracked in .manifest.json).
"""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

import yaml

from ginnungagap.config import HOSTED_PRESETS

HEADER = "# Generated by `ginnungagap render` from ginnungagap.yml - do not edit, the next render overwrites this file.\n"
MANIFEST = ".manifest.json"
DISABLED_URL = "http://disabled.invalid"  # .invalid never resolves: a call to a switched-off service fails loudly

# The Operator's own data, all under the one data volume (see compose.yml).
_OPERATOR_PATHS = {
    "TOPOLOGYOPERATOR_SETTINGS_PROFILES_DIR": "/data/settings_profiles",
    "TOPOLOGYOPERATOR_PROJECTS_DIR": "/data/projects",
    "TOPOLOGYOPERATOR_DESIGN_FILE": "/data/design_state.json",
    "TOPOLOGYOPERATOR_LAYOUT_FILE": "/data/layout.json",
    "TOPOLOGYOPERATOR_LABELS_FILE": "/data/label_layout.json",
    "TOPOLOGYOPERATOR_NOTES_FILE": "/data/node_notes.json",
    "TOPOLOGYOPERATOR_HOLDS_FILE": "/data/holds.json",
    "TOPOLOGYOPERATOR_PROJECT_SELECTIONS": "/data/project_selections.json",
    "TOPOLOGYOPERATOR_DOWNLOAD_DIR": "/data/downloads",
}


class RenderError(RuntimeError):
    """Something the renderer needs is missing (not a problem with the configuration itself)."""


def service_urls(config: dict[str, Any]) -> dict[str, str]:
    """Where each service can be reached from inside the compose network (or the configured address if it runs elsewhere)."""
    services, templates, generator = (
        config["services"],
        config["templates"],
        config["generator"],
    )
    ova = (
        config["ova_deploy"]["external_url"]
        if services["ova_deploy"] == "external"
        else DISABLED_URL
    )
    return {
        "esxi": "http://template-esxi:8000"
        if services["template_esxi"]
        else templates["esxi_url"].rstrip("/"),
        "gns3": "http://template-gns3:8000"
        if services["template_gns3"]
        else templates["gns3_url"].rstrip("/"),
        "generator": "http://generator:8000"
        if services["generator"]
        else generator["url"].rstrip("/"),
        "ova": ova.rstrip("/"),
    }


def profiles(config: dict[str, Any]) -> list[str]:
    services = config["services"]
    result = ["gateway", "ginnungagap"]
    if services["template_esxi"]:
        result += ["template-esxi", "collector-esxi"]
    if services["template_gns3"]:
        result += ["template-gns3", "collector-gns3"]
    if services["generator"]:
        result.append("generator")
    return result


def _env_file(values: dict[str, str]) -> str:
    return HEADER + "".join(f"{key}={value}\n" for key, value in values.items())


def compose_env(config: dict[str, Any]) -> str:
    appliance, templates = config["appliance"], config["templates"]
    store = templates["store"]
    if store["type"] == "nfs":
        nfs = store["nfs"]
        volume = {
            "TEMPLATE_STORE_VOLUME_TYPE": "nfs",
            "TEMPLATE_STORE_VOLUME_OPTS": f"addr={nfs['server']},ro,nfsvers=4,soft,timeo=100",
            "TEMPLATE_STORE_VOLUME_DEVICE": f":{nfs['export']}",
        }
    else:
        volume = {
            "TEMPLATE_STORE_VOLUME_TYPE": "none",
            "TEMPLATE_STORE_VOLUME_OPTS": "bind,ro",
            "TEMPLATE_STORE_VOLUME_DEVICE": store["local"]["path"],
        }
    files = (
        "compose.yml:compose.legacy-ports.yml"
        if appliance["legacy_ports"]
        else "compose.yml"
    )
    return _env_file(
        {
            "COMPOSE_PROJECT_NAME": "ginnungagap",
            "COMPOSE_FILE": files,
            "COMPOSE_PROFILES": ",".join(profiles(config)),
            "TZ": appliance["timezone"],
            "HTTP_PORT": str(appliance["http_port"]),
            "HTTPS_PORT": str(appliance["https_port"]),
            **volume,
            "ESXI_REFRESH_SECONDS": str(templates["esxi_refresh_minutes"] * 60),
            "GNS3_REFRESH_SECONDS": str(templates["gns3_refresh_minutes"] * 60),
            "LOG_LEVEL": config["logging"]["level"],
        }
    )


def operator_env(config: dict[str, Any]) -> str:
    urls = service_urls(config)
    return _env_file(
        {
            "TZ": config["appliance"]["timezone"],
            **_OPERATOR_PATHS,
            # the service addresses TopologyBuilder reads (below the settings file, above its built-in lab addresses)
            "ESXI_TEMPLATE_SERVER_URL": urls["esxi"],
            "GNS3_TEMPLATE_SERVER_URL": urls["gns3"],
            "TOPOLOGY_GENERATOR_URL": urls["generator"],
            "OVA_DEPLOY_URL": urls["ova"],
        }
    )


def caddyfile(config: dict[str, Any]) -> str:
    appliance, services = config["appliance"], config["services"]
    urls = service_urls(config)
    routes = []
    if services["template_esxi"]:
        routes.append(("/templates/esxi/*", "template-esxi:8000"))
    if services["template_gns3"]:
        routes.append(("/templates/gns3/*", "template-gns3:8000"))
    if services["generator"]:
        routes.append(("/generator/*", "generator:8000"))
    if services["ova_deploy"] == "external":
        routes.append(("/ova/*", urls["ova"]))

    lines = [HEADER.rstrip("\n"), ""]
    if appliance["tls"]["mode"] == "self-signed":
        site, tls = urlparse(appliance["public_url"]).hostname, ["tls internal"]
    else:
        lines += ["{", "\tauto_https off", "}", ""]
        site, tls = ":80", []
    lines.append(f"{site} {{")
    lines += [f"\t{line}" for line in tls]
    lines += ["\tencode zstd gzip"]
    auth = appliance["auth"]
    if auth["mode"] == "basic":
        lines += [
            "\tbasic_auth {",
            f"\t\t{auth['user']} {auth['password_hash']}",
            "\t}",
        ]
    for path, upstream in routes:
        lines += [f"\thandle_path {path} {{", f"\t\treverse_proxy {upstream}", "\t}"]
    lines += ["\thandle {", "\t\treverse_proxy ginnungagap:8123", "\t}", "}", ""]
    return "\n".join(lines)


def _key_variable(name: str) -> str:
    return re.sub(r"[^A-Z0-9]", "_", name.upper()) + "_API_KEY"


def generator_config(config: dict[str, Any]) -> dict[str, Any]:
    urls, generator = service_urls(config), config["generator"]
    servers: list[dict[str, Any]] = [
        {"name": s["name"], "url": s["url"], "model": s["model"]}
        for s in generator["llm_servers"]
    ]
    for name, settings in generator["hosted"].items():
        preset = HOSTED_PRESETS.get(name, {})
        servers.append(
            {
                "name": name,
                "type": "openai",
                "base_url": settings.get("base_url") or preset["base_url"],
                "model": settings.get("model") or preset["model"],
                "api_key_env": _key_variable(name),
            }
        )
    return {
        "gns3_api_url": urls["gns3"],
        "template_api_url": urls["esxi"],
        "ollama_servers": servers,
        "max_retries": generator["max_retries"],
        "request_timeout": generator["request_timeout_seconds"],
        "api_timeout": 15,
        "prompt_template_file": "prompt_template.txt",
        "example_topology_file": "example_topology.yml",
    }


def generator_env(config: dict[str, Any]) -> str:
    keys = {
        _key_variable(name): settings["api_key"]
        for name, settings in config["generator"]["hosted"].items()
    }
    return _env_file(keys)


def gns3_collector_config(config: dict[str, Any]) -> dict[str, Any]:
    # no 'servers': the collector reads the hosts from the app's profiles (--profiles-dir)
    return {
        "output_file": "/data/gns3_templates.yml",
        "log_file": "/data/read_gns3.log",
        "request_timeout": 15,
    }


def _write(path: Path, text: str, mode: int = 0o644) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open(
        "w", encoding="utf-8"
    ) as handle:  # truncates in place: the inode stays
        handle.write(text)
    path.chmod(mode)


def render(
    config: dict[str, Any],
    out_dir: str | Path,
    generator_config_dir: str | Path | None = None,
) -> list[str]:
    """
    Writes every file of the enabled services into out_dir and returns their relative paths.
    :raises RenderError: the generator is enabled and its prompt/example files can't be found.
    """
    out = Path(out_dir)
    files: dict[str, tuple[str, int]] = {
        "compose.env": (compose_env(config), 0o644),
        "Caddyfile": (caddyfile(config), 0o644),
        "operator.env": (operator_env(config), 0o644),
    }
    if config["services"]["generator"]:
        source = Path(generator_config_dir) if generator_config_dir else None
        extra = {}
        for name in ("prompt_template.txt", "example_topology.yml"):
            if source is None or not (source / name).is_file():
                raise RenderError(
                    f"{name} of the generator was not found; pass the topology-generator config folder (--generator-config)"
                )
            extra[f"generator/{name}"] = (
                (source / name).read_text(encoding="utf-8"),
                0o644,
            )
        files["generator/topology_config.yml"] = (
            HEADER + yaml.safe_dump(generator_config(config), sort_keys=False),
            0o644,
        )
        files["generator.env"] = (generator_env(config), 0o600)  # holds the API keys
        files.update(extra)
    if config["services"]["template_gns3"]:
        files["collector-gns3/gns3_config.yml"] = (
            HEADER + yaml.safe_dump(gns3_collector_config(config), sort_keys=False),
            0o644,
        )

    previous = _read_manifest(out)
    for name, (text, mode) in files.items():
        _write(out / name, text, mode)
    for stale in sorted(set(previous) - set(files)):
        (out / stale).unlink(missing_ok=True)
        parent = (out / stale).parent
        if parent != out and parent.is_dir() and not any(parent.iterdir()):
            shutil.rmtree(parent)
    _write(out / MANIFEST, json.dumps(sorted(files), indent=2) + "\n")
    return sorted(files)


def _read_manifest(out: Path) -> list[str]:
    try:
        data = json.loads((out / MANIFEST).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    return [
        name
        for name in data
        if isinstance(name, str)
        and not Path(name).is_absolute()
        and ".." not in Path(name).parts
    ]
