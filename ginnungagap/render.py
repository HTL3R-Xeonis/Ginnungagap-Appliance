"""
Turns the one configuration into the files each service reads.

Every service keeps its own native configuration; nothing here couples services, it only writes each one's own file and
the URLs between them. Files are rewritten in place (same inode) because Docker bind-mounts single files by inode, and a
file that is no longer produced is removed again (tracked in .manifest.json).
"""

from __future__ import annotations

import json
import os
import re
import shutil
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

import yaml

from ginnungagap.config import HOSTED_PRESETS

